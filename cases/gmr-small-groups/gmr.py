"""Non-abelian Gyarmati–Matolcsi–Ruzsa inequality (arXiv:2611.12776, arXiv:2611.00156).

For nonempty A_1..A_n in a group: S = A_1...A_n,
N_i = max_{a in A_i} |A_1...A_{i-1} a A_{i+1}...A_n|.
GMR asks whether |S|^(n-1) <= prod N_i. Violation ratio R = |S|^(n-1) / prod N_i > 1.
All counts are exact integers; the ratio comparison is done with Python integers.
"""
import numpy as np
from fractions import Fraction


class Group:
    """Finite group from permutation generators (tuples on 0..d-1). Elements indexed 0..|G|-1, 0 = identity."""
    def __init__(self, gens, d=None):
        d = d or len(gens[0])
        e = tuple(range(d))
        elems = [e]; index = {e: 0}
        frontier = [e]
        while frontier:
            nxt = []
            for x in frontier:
                for g in gens:
                    y = tuple(g[x[i]] for i in range(d))      # y = g o x  (apply x then g)
                    if y not in index:
                        index[y] = len(elems); elems.append(y); nxt.append(y)
            frontier = nxt
        self.elems, self.index, self.d = elems, index, d
        n = len(elems)
        # mult[i, j] = elems[i] * elems[j], with (p*q)(k) = p(q(k)) (apply q then p)
        self.mult = np.empty((n, n), dtype=np.int32)
        for i, p in enumerate(elems):
            for j, q in enumerate(elems):
                self.mult[i, j] = index[tuple(p[q[k]] for k in range(d))]
        self.order = n
        self.inv = np.array([int(np.nonzero(self.mult[i] == 0)[0][0]) for i in range(n)])

    def el(self, perm):
        return self.index[tuple(perm)]


def direct_product(G1, G2):
    """Return a lightweight group object for G1 x G2 (element (i,j) -> i*|G2|+j)."""
    class P: pass
    P = P()
    n1, n2 = G1.order, G2.order
    I = np.arange(n1 * n2)
    a, b = I // n2, I % n2
    P.mult = (G1.mult[a[:, None], a[None, :]] * n2 + G2.mult[b[:, None], b[None, :]]).astype(np.int32)
    P.order = n1 * n2
    P.pair = lambda i, j: i * n2 + j
    return P


def prod(mult, X, Y):
    """product set X*Y (index arrays) -> sorted unique index array"""
    if len(X) == 0 or len(Y) == 0:
        return np.array([], dtype=np.int32)
    return np.unique(mult[np.ix_(X, Y)])


def evaluate(mult, sets):
    """returns |S|, [N_i], ratio as Fraction"""
    sets = [np.unique(np.asarray(s, dtype=np.int32)) for s in sets]
    n = len(sets)
    P = [np.array([0], dtype=np.int32)]          # P[i] = A_1..A_i ; P[0] = {e}
    for s in sets:
        P.append(prod(mult, P[-1], s))
    Q = [None] * (n + 2); Q[n + 1] = np.array([0], dtype=np.int32)   # Q[i] = A_i..A_n
    for i in range(n, 0, -1):
        Q[i] = prod(mult, sets[i - 1], Q[i + 1])
    S = len(P[n])
    N = []
    for i in range(1, n + 1):
        left, right = P[i - 1], Q[i + 1]
        best = 0
        for a in sets[i - 1]:
            aR = np.unique(mult[a, right])
            best = max(best, len(prod(mult, left, aR)))
        N.append(best)
    num = S ** (n - 1); den = 1
    for x in N: den *= x
    return S, N, Fraction(num, den)


def cyc(G, g):
    """cyclic subgroup generated by element index g"""
    out = [0]; x = g
    while x != 0:
        out.append(int(x)); x = G.mult[x, g]
    return out
